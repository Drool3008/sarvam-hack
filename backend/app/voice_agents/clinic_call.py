"""The Clinic agent's call runner (README "Acting" stage; prompt.md section 9
Clinic agent row; the README's "The phone call, not the room").

`run_clinic_call()` drives one clinic-booking episode end to end: dial the
ranked clinic list with the redial-then-fallback rule, run the live-call
dialogue against either a real telephony leg (`transport="telephony"`) or a
scripted receptionist (`transport="local"`), and hand the confirmed slot to
the affected person rather than closing it on the agent's own word.

Rule 2: every agent-authored line is generated by `sarvam-105b-conversations`
through `app.sarvam.conversations` and passes `refusal.enforce()` before it
is "spoken" (stored and added to the transcript). The receptionist's lines,
and the affected person's own hand-off confirmation, are other people's
words — stored verbatim, never run through the validator.
"""

from __future__ import annotations

import json
from dataclasses import asdict, dataclass, field
from pathlib import Path
from typing import Literal

from .. import audit, store
from ..assess import refusal
from ..domain import Booking, Call, Household, Person, Provider, Utterance
from ..sarvam import conversations
from . import platform

FIXTURES = Path(__file__).resolve().parents[2] / "fixtures"
RECEPTIONIST_FIXTURE = FIXTURES / "clinic_receptionist.json"

Transport = Literal["local", "telephony"]

SYSTEM_PROMPT_BASE = """You are the Family Health Agent, speaking on a live phone call for one household.

ROLE
You keep the household's medicines, appointments and records running. You are on a
call, so you speak plainly and briefly.

THE FOUR ROLES
- affected person: the person this call concerns.
- responsible person: owns the wallet and holds a veto, used only on disagreement.
- contact chain: ranked by who can make a sound decision, not by age.
- family group: told that something happened, never the medical detail.

THE THREE REFUSALS
You never name a condition. You never suggest a dose. You never substitute a
medicine. Each of those goes to a human. If a question needs any of them, you say
it goes to a person and you escalate.

SEVERITY
If the factors disagree, or you cannot tell, you go up a tier and ask a human. You
never guess downward.

THE HAND-OFF
When a person answers the clinic, hand the line to the affected person. The parent
confirms their own appointment, in their own language.

WORDS
Keep the person's words verbatim. Do not tidy them, summarise them into your own
words, or add anything they did not say.

LANGUAGE AND PACE
Speak in the person's preferred language, at a slower pace for an elderly listener.
If you cannot speak their language, say so and hand the call to a family member."""


def _clinic_goal(reason: str, requested_window: str, affected_name: str, clinic_name: str) -> str:
    return (
        "\n\nCLINIC CALL GOAL\n"
        f"You are calling {clinic_name} to book the earliest slot in the window "
        f"'{requested_window}' for {affected_name}. State the reason only as the "
        f'family itself stated it, in those words: "{reason}". Do not add a '
        "diagnosis, a cause, or any detail the family did not give you. If the "
        "clinic offers no slot in that window, accept the next slot it offers. "
        "When someone at the clinic is ready to confirm a time, say that you "
        "will bring the parent onto the line so they can confirm it themselves."
    )


def _load_scenarios() -> dict:
    return json.loads(RECEPTIONIST_FIXTURE.read_text(encoding="utf-8"))


@dataclass
class ClinicCallResult:
    episode_id: str
    household_id: str
    transport: Transport
    source: Literal["sarvam", "mock"]
    scenario: str | None
    transcript: list[dict] = field(default_factory=list)
    clinic_reached: dict | None = None
    fell_through: bool = False
    fallback_reason: str | None = None
    booking: dict | None = None
    call_ids: list[str] = field(default_factory=list)
    escalated: bool = False
    escalation_reason: str | None = None
    attempt_id: str | None = None


def booking_to_dict(b: Booking) -> dict:
    d = asdict(b)
    d["created_at"] = b.created_at.isoformat()
    return d


def call_to_dict(c: Call) -> dict:
    d = asdict(c)
    d["created_at"] = c.created_at.isoformat()
    return d


def _provider_dict(p: Provider) -> dict:
    return {"id": p.id, "name": p.name, "rank": p.rank, "phone_e164": p.phone_e164}


def run_clinic_call(
    household_id: str,
    episode_id: str,
    reason: str,
    requested_window: str,
    transport: Transport = "local",
    scenario: str = "offers_slot",
) -> ClinicCallResult:
    """Book the earliest slot in `requested_window` for the household's
    affected person, following the README's failure rules for an
    unreachable clinic and a missing slot.

    `transport="local"` runs the whole dialogue against the scripted
    receptionist named by `scenario` (see fixtures/clinic_receptionist.json)
    so the behaviour is exercisable without a telephony account — the
    result's `transport` field says so plainly, and `source` is tagged
    "mock" whenever the underlying model call itself ran mocked, so a local
    run is never presentable as a real phone call.

    `transport="telephony"` places the call through `platform.place_call()`.
    `platform.IndusNotConfigured` is not caught here — it is surfaced to the
    caller, per the brief.
    """
    hh = store.household(household_id)
    if hh is None:
        raise ValueError(f"unknown household {household_id!r}")

    affected = hh.affected_person()
    if affected is None:
        raise ValueError("household has no affected person on record")

    clinics = hh.clinics()
    if not clinics:
        raise ValueError("household has no clinics on record")

    if transport == "telephony":
        return _run_telephony(hh, affected, clinics[0], episode_id, reason, requested_window)
    return _run_local(hh, affected, clinics, episode_id, reason, requested_window, scenario)


# --------------------------------------------------------------------------- #
# Telephony transport
# --------------------------------------------------------------------------- #


def _run_telephony(
    hh: Household,
    affected: Person,
    clinic: Provider,
    episode_id: str,
    reason: str,
    requested_window: str,
) -> ClinicCallResult:
    audit.record(
        "clinic_call_requested",
        actor="agent:clinic",
        data_source="voice_agents_platform",
        episode_id=episode_id,
        household_id=hh.id,
        clinic_id=clinic.id,
        transport="telephony",
    )
    variables = {
        "reason": reason,
        "requested_window": requested_window,
        # The variable call_transfer hands the line to, per the README's
        # "the phone call, not the room" — the parent confirms their own
        # appointment, in their own language, not the agent on their behalf.
        "affected_person_phone": affected.phone_e164,
        "affected_person_name": affected.name,
        "affected_person_language": affected.preferred_language,
    }
    # Raises platform.IndusNotConfigured in this environment (no Indus
    # workspace vars are set) — deliberately not caught here, per the brief.
    placed = platform.place_call(agent="clinic", to_phone=clinic.phone_e164, variables=variables)

    # OPEN: everything past a successfully placed call — the connected/
    # no-answer/busy outcome, the live dialogue, the hand-off, the resulting
    # Call/Booking rows — arrives through the instant-outbound webhook and
    # the on-end hook (prompt.md section 9, "Webhooks and the contact
    # chain"), which lives in `workers/` and is out of this module's scope.
    # This function cannot go further without a reachable Indus workspace.
    return ClinicCallResult(
        episode_id=episode_id,
        household_id=hh.id,
        transport="telephony",
        source="sarvam",
        scenario=None,
        clinic_reached=_provider_dict(clinic),
        attempt_id=placed.get("attempt_id"),
    )


# --------------------------------------------------------------------------- #
# Local transport — the scripted receptionist
# --------------------------------------------------------------------------- #


def _record_call_attempt(
    episode_id: str, clinic: Provider, status: str, connected: bool
) -> Call:
    call = Call.new(
        episode_id=episode_id,
        agent="clinic",
        attempt_id=None,
        interaction_id=None,
        to_phone=clinic.phone_e164,
        status=status,
        duration=0.0 if not connected else None,
        final_agent_variables={},
        recording_ref=None,
    )
    return store.add_call(call)


def _run_local(
    hh: Household,
    affected: Person,
    clinics: list[Provider],
    episode_id: str,
    reason: str,
    requested_window: str,
    scenario: str,
) -> ClinicCallResult:
    scenarios = _load_scenarios()
    if scenario not in scenarios:
        raise ValueError(f"unknown receptionist scenario {scenario!r}")
    scenario_data = scenarios[scenario]

    transcript: list[dict] = []
    call_ids: list[str] = []
    connected_clinic: Provider | None = None
    fell_through = False
    fallback_reason: str | None = None

    for idx, clinic in enumerate(clinics):
        is_first_clinic = idx == 0
        # README / prompt.md section 9: redial the same clinic once before
        # falling to the next rank. No redial is specified for the fallback
        # clinic itself.
        redials = 2 if is_first_clinic else 1
        connected_here = False
        for attempt in range(1, redials + 1):
            connects = bool(scenario_data.get("connects"))
            status = "connected" if connects else scenario_data.get("outcome", "no_answer")
            call = _record_call_attempt(episode_id, clinic, status, connects)
            call_ids.append(call.id)
            audit.record(
                "clinic_call_attempt",
                actor="agent:clinic",
                data_source="clinic_call_local",
                episode_id=episode_id,
                household_id=hh.id,
                clinic_id=clinic.id,
                clinic_rank=clinic.rank,
                attempt=attempt,
                outcome=status,
            )
            if connects:
                connected_here = True
                transcript.append({"speaker": "system", "text": f"{clinic.name} answers."})
                break
            transcript.append(
                {
                    "speaker": "system",
                    "text": f"{clinic.name}: {status.replace('_', ' ')} (attempt {attempt}).",
                }
            )
        if connected_here:
            connected_clinic = clinic
            break
        if idx < len(clinics) - 1:
            fell_through = True
            fallback_reason = f"{clinic.name} (rank {clinic.rank}) did not answer after redial"

    if connected_clinic is None:
        booking = Booking(
            episode_id=episode_id,
            provider_id=clinics[-1].id,
            slot="",
            confirmed_by_name=None,
            status="dead_end",
            note=(
                "No clinic answered: "
                + ", ".join(f"{c.name} (rank {c.rank})" for c in clinics)
                + ". Reporting the dead end rather than stopping silently."
            ),
        )
        store.add_booking(booking)
        audit.record(
            "clinic_dead_end",
            actor="agent:clinic",
            data_source="clinic_call_local",
            episode_id=episode_id,
            household_id=hh.id,
        )
        return ClinicCallResult(
            episode_id=episode_id,
            household_id=hh.id,
            transport="local",
            source="mock",  # no model call was made on a dead-end chain
            scenario=scenario,
            transcript=transcript,
            clinic_reached=None,
            fell_through=True,
            fallback_reason="no clinic answered",
            booking=booking_to_dict(booking),
            call_ids=call_ids,
        )

    return _run_dialogue(
        hh=hh,
        affected=affected,
        clinic=connected_clinic,
        episode_id=episode_id,
        reason=reason,
        requested_window=requested_window,
        scenario=scenario,
        scenario_data=scenario_data,
        transcript=transcript,
        call_ids=call_ids,
        fell_through=fell_through,
        fallback_reason=fallback_reason,
    )


def _run_dialogue(
    *,
    hh: Household,
    affected: Person,
    clinic: Provider,
    episode_id: str,
    reason: str,
    requested_window: str,
    scenario: str,
    scenario_data: dict,
    transcript: list[dict],
    call_ids: list[str],
    fell_through: bool,
    fallback_reason: str | None,
) -> ClinicCallResult:
    receptionist_turns = scenario_data.get("receptionist_turns", [])
    goal = _clinic_goal(reason, requested_window, affected.name, clinic.name)
    messages: list[dict[str, str]] = [{"role": "system", "content": SYSTEM_PROMPT_BASE + goal}]

    state = {"source": "mock", "escalated": False, "escalation_reason": None}

    def _escalated_result(booking: Booking | None) -> ClinicCallResult:
        return ClinicCallResult(
            episode_id=episode_id,
            household_id=hh.id,
            transport="local",
            source=state["source"],
            scenario=scenario,
            transcript=transcript,
            clinic_reached=_provider_dict(clinic),
            fell_through=fell_through,
            fallback_reason=fallback_reason,
            booking=booking_to_dict(booking) if booking else None,
            call_ids=call_ids,
            escalated=True,
            escalation_reason=state["escalation_reason"],
        )

    def _hear_receptionist(line: str) -> None:
        store.add_utterance(
            Utterance.new(
                episode_id=episode_id,
                verbatim_text=line,
                language="en-IN",
                speaker_label="receptionist",
                audio_ref=None,
                stt_job_id=None,
            )
        )
        transcript.append({"speaker": "receptionist", "text": line})
        messages.append({"role": "user", "content": line})

    def _speak_agent() -> str | None:
        """Generate, validate and emit one agent turn. Returns the text, or
        None (having recorded the escalation) if it violated a refusal — the
        line is never added to the transcript or spoken in that case."""
        turn = conversations.next_turn(messages)
        state["source"] = turn.source
        try:
            text = refusal.enforce(
                turn.text,
                condition_labels=hh.condition_labels,
                prescribed_medicines=hh.medicine_names(),
                # OPEN: no medicine-name NER runs over live-call text in this
                # slice (see app/api/intake.py's lexicon heuristic for the
                # same gap on the voice-note summary) — the substitution
                # check below is a placeholder until one lands.
                candidate_medicines=[],
            )
        except refusal.RefusalViolation as exc:
            audit.record(
                "clinic_call_refusal_violation",
                actor="agent:clinic",
                data_source="sarvam-105b-conversations",
                episode_id=episode_id,
                household_id=hh.id,
                clinic_id=clinic.id,
                violations=list(exc.verdict.violations),
            )
            state["escalated"] = True
            state["escalation_reason"] = "; ".join(exc.verdict.violations)
            return None
        store.add_utterance(
            Utterance.new(
                episode_id=episode_id,
                verbatim_text=text,
                language=affected.preferred_language,
                speaker_label="agent",
                audio_ref=None,
                stt_job_id=None,
            )
        )
        transcript.append({"speaker": "agent", "text": text})
        messages.append({"role": "assistant", "content": text})
        return text

    # Turn 1: the receptionist answers, the agent opens the call.
    if receptionist_turns:
        _hear_receptionist(receptionist_turns[0])
    if _speak_agent() is None:
        return _escalated_result(None)

    # Turn 2: the receptionist offers a slot, or says there is none in the
    # requested window.
    if len(receptionist_turns) > 1:
        _hear_receptionist(receptionist_turns[1])
    if _speak_agent() is None:
        return _escalated_result(None)

    # The booking decision is read off the fixture's structured fields, not
    # parsed out of the model's generated line — the dialogue text is for
    # the call, the booking record is deterministic.
    offered_slot = scenario_data.get("offered_slot", "")
    in_window = bool(scenario_data.get("in_requested_window", True))
    note = (
        None
        if in_window
        else (
            f"No slot available in the requested window ({requested_window}); "
            f"took the next option offered: {offered_slot}."
        )
    )
    booking = Booking(
        episode_id=episode_id,
        provider_id=clinic.id,
        slot=offered_slot,
        confirmed_by_name=None,
        status="held",
        note=note,
    )
    store.add_booking(booking)
    audit.record(
        "booking_held",
        actor="agent:clinic",
        data_source="clinic_call_local",
        episode_id=episode_id,
        household_id=hh.id,
        clinic_id=clinic.id,
        slot=offered_slot,
        in_requested_window=in_window,
    )

    # Turn 3: the receptionist confirms and the agent signals the hand-off.
    if len(receptionist_turns) > 2:
        _hear_receptionist(receptionist_turns[2])
    if _speak_agent() is None:
        return _escalated_result(booking)

    # The hand-off itself (README "the phone call, not the room"): under
    # transport="local" this is a recorded turn, not a model call — the
    # affected person's own words, so they are stored like the
    # receptionist's, never run through refusal.enforce(). A slot never
    # reaches "confirmed" without this named human turn.
    confirmation_text = (
        f"Yes, this is {affected.name}. I confirm the appointment at {offered_slot}."
    )
    store.add_utterance(
        Utterance.new(
            episode_id=episode_id,
            verbatim_text=confirmation_text,
            language=affected.preferred_language,
            speaker_label="affected_person",
            audio_ref=None,
            stt_job_id=None,
        )
    )
    transcript.append({"speaker": "affected_person", "text": confirmation_text})

    booking.status = "confirmed"
    booking.confirmed_by_name = affected.name
    audit.record(
        "booking_confirmed",
        actor=affected.id,
        data_source="clinic_call_local",
        episode_id=episode_id,
        household_id=hh.id,
        clinic_id=clinic.id,
        confirmed_by_name=affected.name,
    )

    return ClinicCallResult(
        episode_id=episode_id,
        household_id=hh.id,
        transport="local",
        source=state["source"],
        scenario=scenario,
        transcript=transcript,
        clinic_reached=_provider_dict(clinic),
        fell_through=fell_through,
        fallback_reason=fallback_reason,
        booking=booking_to_dict(booking),
        call_ids=call_ids,
    )
